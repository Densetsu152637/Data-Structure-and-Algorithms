
import random
from modular_exponent import mod_exp

SMALL_PRIMES = [2, 3, 5, 7, 11, 13, 17, 19, 23]

def is_probable_prime(n: int, k: int = 10) -> bool:
    """
    Miller-Rabin primality test.
    n : number to test for primality
    k : number of test rounds (higher = more accurate)
    """
    # early case testing
    if n <= 1:
        return False
    if n <= 3:
        return True
    
    # checks some early prime numbers for small optimisations
    for v in SMALL_PRIMES:
        if n % v == 0:
            return False
        
    # we have a guaranteed n is odd call from outside the function
    # so we can employ observation 1 from the slides
    # Observation 1: write n - 1 = 2^s * t, with t odd    
    t = n - 1
    s = 0
    while t % 2 == 0:
        t //= 2
        s += 1
        
    # Fermat Tests  
    k = max(1, k)
    # Repeat k tests
    for _test in range(k):
        a = random.randrange(2, n - 2)

        # Compute x0 = a^t mod n
        x = mod_exp(a, t, n)

        if x == 1:
            # Case 4: all xi = 1 -> probably prime
            continue

        # Square repeatedly: xi = (x_{i-1})^2 mod n
        stack = [x]
        probably_prime = True
        for test_num in range(s):
            x = mod_exp(x, 2, n)
            if stack[-1] != -1 and x == 1:
                # Case 2: xs-1 != 1 and xs == 1 -> composite
                return False
            elif stack[-1] == -1 and x == 1:
                # Case 3: xs-1 == 1 and xs == 1 -> probably prime
                # stack[-1] == -1
                break
            stack.append(x)
            
        # Case 1: xs != 1 -> composite
        probably_prime = probably_prime and stack[-1] == 1
        
        if not probably_prime:
            return False

    return True

def generate_prime(d: int) -> tuple[int, int]:
    """
    Generate a random prime number with exactly d digits.
    returns (prime, loops), where
    prime: number generated by the algorithm
    loops: how many iterations it took to produce the prime
    """
    if d <= 0: raise ValueError("Number of digits must be positive.")
    
    lower = 10 ** (d - 1)
    upper = 10 ** d // 2 - 1
    
    iterations = 1
    while True:
        # Ensure odd number
        candidate = 2 * random.randrange(lower, upper) + 1
        if is_probable_prime(candidate):
            break
        iterations += 1

    return (candidate, iterations)